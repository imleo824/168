#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const OUTPUT_PATH = path.join(ROOT, 'artifacts/post-main-chain-audit.md');
const FILES = {
  bootstrap: 'server/bootstrap.ts',
  postRoutes: 'server/routes/post.routes.ts',
  postService: 'server/services/post/index.ts',
  postModule: 'server/modules/post/index.ts',
};

const HTTP_METHOD_PATTERN = /app\.(get|post|put|patch|delete)\(\s*['"]([^'"]+)['"]/g;
const POST_ROUTE_PATTERN = /^\/api\/(posts|post|comments|quotes)(?:\/|$)/;
const PRISMA_MODEL_PATTERN = /prisma\.([A-Za-z_$][\w$]*)\./g;
const STATIC_METHOD_PATTERN = /static\s+async\s+([A-Za-z_$][\w$]*)\s*\(/g;
const FUNCTION_PATTERN = /(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(/g;

async function read(relativePath) {
  return fs.readFile(path.join(ROOT, relativePath), 'utf8').catch(() => '');
}

function lineCount(content) {
  return content ? content.split(/\r?\n/).length : 0;
}

function collectRoutes(content) {
  const routes = [];
  let match;
  while ((match = HTTP_METHOD_PATTERN.exec(content))) {
    const route = match[2];
    if (POST_ROUTE_PATTERN.test(route)) {
      routes.push({ method: match[1].toUpperCase(), route });
    }
  }
  return routes;
}

function countPrismaModels(content) {
  const counts = new Map();
  let match;
  while ((match = PRISMA_MODEL_PATTERN.exec(content))) {
    const model = match[1];
    counts.set(model, (counts.get(model) || 0) + 1);
  }
  return Array.from(counts.entries()).sort((a, b) => b[1] - a[1]);
}

function collectStaticMethods(content) {
  const names = [];
  let match;
  while ((match = STATIC_METHOD_PATTERN.exec(content))) names.push(match[1]);
  return names;
}

function collectTopLevelFunctions(content) {
  const names = [];
  let match;
  while ((match = FUNCTION_PATTERN.exec(content))) names.push(match[1]);
  return names;
}

function formatRoutes(routes) {
  if (routes.length === 0) return '- none detected';
  return routes.map((item) => `- ${item.method} ${item.route}`).join('\n');
}

function formatCounts(counts) {
  if (counts.length === 0) return '- none detected';
  return counts.slice(0, 30).map(([model, count]) => `- ${model}: ${count}`).join('\n');
}

function formatNames(names, max = 80) {
  if (names.length === 0) return '- none detected';
  return names.slice(0, max).map((name) => `- ${name}`).join('\n');
}

function buildFindings({ bootstrapRoutes, postRoutes, postServiceLines, postServicePrismaCounts, postServiceMethods }) {
  const findings = [];

  if (bootstrapRoutes.length > 0) {
    findings.push('Post main-chain routes are still present in `server/bootstrap.ts`; they should be migrated into `server/routes/post.routes.ts` in small PRs.');
  }

  if (postRoutes.length <= 1) {
    findings.push('`server/routes/post.routes.ts` currently protects only a narrow slice of the post surface; detail and interaction routes still need module ownership.');
  }

  if (postServiceLines > 1200) {
    findings.push('`server/services/post/index.ts` is still a large god service; split interaction, view, quote, and ranking context responsibilities before adding more features.');
  }

  const heavyModels = postServicePrismaCounts.filter(([, count]) => count >= 5).map(([model]) => model);
  if (heavyModels.length > 0) {
    findings.push(`PostService has concentrated Prisma access for ${heavyModels.join(', ')}; introduce repositories before moving handlers.`);
  }

  const interactionMethods = postServiceMethods.filter((name) => /like|share|view|quote|comment|feedback|ranking/i.test(name));
  if (interactionMethods.length >= 5) {
    findings.push('PostService mixes feed ranking, interaction writes, view dedupe, and quote/comment behavior; this is the next highest-risk backend boundary.');
  }

  return findings;
}

async function main() {
  const [bootstrap, postRoutesContent, postService, postModule] = await Promise.all([
    read(FILES.bootstrap),
    read(FILES.postRoutes),
    read(FILES.postService),
    read(FILES.postModule),
  ]);

  const bootstrapRoutes = collectRoutes(bootstrap);
  const postRoutes = collectRoutes(postRoutesContent);
  const postServicePrismaCounts = countPrismaModels(postService);
  const postServiceMethods = collectStaticMethods(postService);
  const helperFunctions = collectTopLevelFunctions(postService);
  const findings = buildFindings({
    bootstrapRoutes,
    postRoutes,
    postServiceLines: lineCount(postService),
    postServicePrismaCounts,
    postServiceMethods,
  });

  const markdown = `# Post Main Chain Audit\n\nGenerated by \`scripts/post-main-chain-audit.mjs\`.\n\n## Summary\n\n| Area | Value |\n| --- | ---: |\n| bootstrap post-like routes | ${bootstrapRoutes.length} |\n| post.routes.ts post-like routes | ${postRoutes.length} |\n| PostService lines | ${lineCount(postService)} |\n| PostService static methods | ${postServiceMethods.length} |\n| PostService helper functions | ${helperFunctions.length} |\n| post module bytes | ${postModule.length} |\n\n## Highest-priority findings\n\n${findings.length > 0 ? findings.map((item) => `- ${item}`).join('\n') : '- No high-priority post main-chain findings detected.'}\n\n## Post routes still in bootstrap.ts\n\n${formatRoutes(bootstrapRoutes)}\n\n## Post routes in server/routes/post.routes.ts\n\n${formatRoutes(postRoutes)}\n\n## PostService Prisma model concentration\n\n${formatCounts(postServicePrismaCounts)}\n\n## PostService static methods\n\n${formatNames(postServiceMethods)}\n\n## PostService helper functions\n\n${formatNames(helperFunctions, 120)}\n\n## Recommended migration order\n\n1. Move post detail read route into \`server/routes/post.routes.ts\` without changing response shape.\n2. Move view recording route into a small interaction module, preserving view dedupe.\n3. Move like/share writes into a post interaction service/repository, preserving ranking refresh and bumpedAt behavior.\n4. Move quote/comment reads and writes only after interaction guard passes.\n5. Ratchet route/bootstrap boundaries only after audit + build pass.\n`;

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, markdown, 'utf8');

  console.log('\n=== Post Main Chain Audit ===');
  console.log(`bootstrap post-like routes: ${bootstrapRoutes.length}`);
  console.log(`post.routes.ts post-like routes: ${postRoutes.length}`);
  console.log(`PostService lines: ${lineCount(postService)}`);
  console.log(`PostService static methods: ${postServiceMethods.length}`);
  console.log(`Report written to ${path.relative(ROOT, OUTPUT_PATH)}`);
}

main().catch((error) => {
  console.error('[post-main-chain-audit] failed:', error);
  process.exitCode = 1;
});
